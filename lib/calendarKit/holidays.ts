/** 'YYYY-MM-DD' (0 채움) */
export const ymdKey = (d: Date) =>
  `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;

/** 그 날의 공휴일 이름(한국어 화면에서만) */
export function getHoliday(d: Date): string | undefined {
  return getLang() === 'ko' ? HOLIDAYS[ymdKey(d)] : undefined;
}

